#!/usr/bin/env python3
"""Make one host canonical per publication, at the edge.

Why this exists
---------------
Search Readiness checklist item a1 -- "One canonical host; every other host
301s to it" -- failed on 25 Oct 2026 for professionalresourcelibrary.com and
founderoperatorlibrary.com: https://www.<domain>/ answered 200 rather than a
301 to the apex. Both hosts are custom domains on the same Cloudflare Pages
project, so Pages serves the identical tree on both and Google sees two sites
splitting one site's signals. A <link rel="canonical"> is a hint; a 301 is not.

Why a Pages Function and not _redirects
---------------------------------------
Cloudflare Pages `_redirects` matches on PATH only -- there is no way to express
"when the Host header is www". A Pages Function sees the request URL including
its host, so the rule can live in the repository instead of as hand-made
Cloudflare dashboard state nobody can review in a diff.

Each publication's Pages project has its root directory set to the publication
folder (docs/DAY-1-LAUNCH.md step 3), so `functions/_middleware.js` inside that
folder is the project's middleware and runs on every request to it.

Generated, never hand-edited: the canonical host comes from
data/publications.json `working_domain`, so adding a publication or moving a
domain cannot leave a stale redirect behind.
scripts/validators/validate_host_canonicalization.py checks the published tree
against this generator.

    python3 scripts/build_host_canonicalization.py [--write]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from lib.text_io import write_lf  # noqa: E402

MIDDLEWARE_REL = "functions/_middleware.js"


def middleware(domain: str, title: str) -> str:
    """The Pages middleware that 301s every other host to `domain`.

    308 would preserve the method, but a1 asks for 301/308 and 301 is what
    Google's documentation calls a permanent redirect for canonicalisation; a
    GET is all a crawler sends to a content host anyway.

    Only the host is rewritten. Path, query and hash are carried over untouched,
    so a deep link keeps working and the redirect never collapses to the root --
    the mistake that makes a www redirect worse than no redirect at all.
    """
    return f"""// GENERATED by scripts/build_host_canonicalization.py -- do not edit by hand.
//
// {title}: {domain} is the one canonical host. Every other host that Cloudflare
// Pages serves this project on (www, the *.pages.dev preview host, any alias)
// answers 301 to the same path on {domain}, so the two hosts stop splitting one
// site's signals. Checklist item a1.
//
// Pages `_redirects` cannot express this: it matches the path only. Middleware
// sees the whole URL, host included.

const CANONICAL_HOST = {json.dumps(domain)};

export async function onRequest(context) {{
  const url = new URL(context.request.url);
  if (url.hostname === CANONICAL_HOST) return context.next();
  url.hostname = CANONICAL_HOST;
  url.port = "";
  url.protocol = "https:";
  return Response.redirect(url.toString(), 301);
}}
"""


def plan() -> dict[str, str]:
    """{repo-relative path: wanted contents} for every publication."""
    pubs = json.loads((ROOT / "data/publications.json").read_text(encoding="utf-8"))
    out: dict[str, str] = {}
    for pub in pubs:
        domain = (pub.get("working_domain") or "").strip().lower()
        if not domain:
            raise SystemExit(f"data/publications.json: '{pub.get('id')}' has no working_domain")
        if domain.startswith("www."):
            raise SystemExit(
                f"data/publications.json: '{pub.get('id')}' working_domain is {domain!r}; "
                "the canonical host is the apex, so a www working_domain would redirect to itself")
        out[f"{pub['folder']}/{MIDDLEWARE_REL}"] = middleware(domain, pub["title"])
    return out


def main() -> int:
    write = "--write" in sys.argv
    wanted = plan()
    drift = []
    for rel, body in sorted(wanted.items()):
        path = ROOT / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != body:
            drift.append(rel)
            if write:
                path.parent.mkdir(parents=True, exist_ok=True)
                write_lf(path, body)
    print(f"HOST CANONICALIZATION: {len(wanted)} publication(s)")
    for rel in drift:
        print(f"  {'WROTE' if write else 'DRIFT'} {rel}")
    if not wanted:
        print("HOST CANONICALIZATION: FAIL - no publications")
        return 1
    if drift and not write:
        print(f"HOST CANONICALIZATION: {len(drift)} file(s) out of step; run with --write")
        return 1
    print("HOST CANONICALIZATION: " + ("wrote " + str(len(drift)) + " file(s)" if write else "in step"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
